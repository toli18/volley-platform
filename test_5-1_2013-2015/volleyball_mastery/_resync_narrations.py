def write_lines(path: Path, header: str, rows: list[tuple[float, str]]) -> None:
    lines = [header]
    for start, text in rows:
        lines.append(f"{start:.2f} | {text}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def rows_from_vtt(vtt: Path, texts: list[str]) -> list[tuple[float, str]]:
    merged = merge_cues(parse_vtt(vtt), max_gap=0.35, max_chars=72)
    if len(texts) != len(merged):
        raise ValueError(f"{vtt.name}: need {len(merged)} lines, got {len(texts)}")
    return [(start, text) for (start, _en), text in zip(merged, texts)]


