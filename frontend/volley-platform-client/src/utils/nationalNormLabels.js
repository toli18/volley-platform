/** Етикети за сравнение с националното тестване БФВ 2022. */

export function national2022RefLabel(gender) {
  if (gender === "female") return "нац. 2022 · момичета 13–14 г.";
  if (gender === "male") return "нац. 2022 · момчета 14–15 г.";
  return "нац. тестване 2022";
}

export function national2022ChipTitle(gender) {
  if (gender === "female") {
    return "Сравнение с национално тестване 2022 — момичета 13–14 г. (ориентир)";
  }
  if (gender === "male") {
    return "Сравнение с национално тестване 2022 — момчета 14–15 г. (ориентир)";
  }
  return "Сравнение с национално тестване БФВ 2022 (ориентир)";
}

export const NATIONAL_2022_DISCLAIMER =
  "Сравнението „нац. 2022“ е спрямо националното тестване на БФВ от 2022 г.: " +
  "момичета 13–14 г. и момчета 14–15 г. „% връстници“ показва мястото спрямо другите " +
  "на същата възраст и пол (при малка извадка — *). Това са ориентири и не променят официалната оценка.";
