def mini_program_7_lessons() -> str:
    return """## Програма от 7 урока (мини-волейбол в училище)

Моделът е за **50–60 минути**, **1 урок седмично**, група **20–25 деца**. Цел: запознаване с топката, основни техники и игра в малки формати.

### Съдържание по уроци (A–E)
- **A** — Подаване (palleggio)
- **B** — Прием отдолу (bagher)
- **C** — Сервис отдолу
- **D** — Атака / рязка (от 4. клас нагоре)
- **E** — Подготовка за „мач“ / турнир

### Примерна матрица (3. клас)
| Урок | Фокус | Игра |
|------|--------|------|
| 1 | Представяне, правила, игри с хвърляне | Ловци и зайци, Изпразни залата |
| 2 | Подаване — ръце, контакт | Кръг в подаване, 1v1 |
| 3 | Прием, движение с крака | Огледало, 2v2 |
| 4 | Сервис отдолу | Мишени, 3v3 с ротация |
| 5 | Сервис + подготовка за рязка | 4v4 |
| 6 | Атака (където е подходящо) | 4v4 с излизане в сервис |
| 7 | Обобщение | Симулация на турнир |

### Принципи
- Много **докосвания** и малки групи (1v1 → 4v4).
- Ротация след точка — от ранна възраст.
- Турнир между класове в края на цикъла — мотивация.

### За треньора
- Ясен протокол: фигура за начало/край, един свиркалка.
- Игри с **цели** (кош, кръг, зона), не само „пасане“.
"""


def methodology_organization() -> str:
    return """## Организация на тренировъчната сесия

### Стандартна структура (90–120 мин)
1. **Въведение (10–15 мин)** — цел на деня, разгрявка с топка, правила на упражнението.
2. **Технически блок (20–25 мин)** — един фокус; висок брой повторения; кратка обратна връзка.
3. **Комплексен / игрови блок (25–35 мин)** — свързване на техниката в ритъм, ротации, натиск.
4. **Игра или физически блок (15–20 мин)** — контролиран интензитет.
5. **Заключение (5–10 мин)** — какво научихме, домашно (по желание), разтягане.

### Натоварване
- Следвайте **седмичния мезо план** — не качвайте и обем, и интензитет в един ден.
- След мач — намалете обема с **20–30%**; акцент върху възстановяване.

### Комуникация
- Максимум **3 команди** на ротация за U14; при мини — още по-кратки сигнали.
- Капитан на пода и в защита — ясни роли.
"""


