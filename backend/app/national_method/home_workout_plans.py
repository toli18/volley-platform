def _age_band_for_athlete(birth_year: Optional[int], gender: Optional[str] = None) -> str:
    if not birth_year:
        return "U14"
    from datetime import date

    age = date.today().year - int(birth_year)
    return resolve_age_band({"age": age, "gender": gender})


def _focus_lines(main_focus: str, secondary_focus: Optional[str]) -> list[str]:
    lines: list[str] = []
    for key in (main_focus, secondary_focus):
        if not key:
            continue
        block = _FOCUS_HOME_BLOCKS.get(key)
        if block:
            lines.append(f"**{key}**")
            lines.extend(f"- {x}" for x in block)
    if not lines:
        lines.append("**Общ акцент**")
        lines.extend(f"- {x}" for x in _DEFAULT_FOCUS)
    return lines


def build_home_workout_text(
    *,
    athlete_name: str,
    birth_year: Optional[int] = None,
    gender: Optional[str] = None,
    main_focus: str,
    secondary_focus: Optional[str] = None,
    duration_min: int = 30,
) -> str:
    """Сглобява естествен текстов план за вкъщи (без Drill библиотека)."""
    total = max(20, min(45, int(duration_min)))
    age_band = _age_band_for_athlete(birth_year, gender)
    knowledge = get_age_knowledge(age_band)
    principles = (knowledge.get("principles") or [])[:3]
    cues = (knowledge.get("coach_cues") or [])[:3]

    # Грубо разпределение на минутите.
    warm = max(4, total // 7)
    coord = max(5, total // 5)
    phys = max(5, total // 5)
    plyo = max(5, total // 6)
    focus = max(5, total - warm - coord - phys - plyo - 3)
    cool = 3

    lines = [
        f"# Домашна тренировка — {athlete_name}",
        f"**Възрастова група (методика):** {age_band} · **Продължителност:** ~{total} мин",
        f"**Условия:** вкъщи / двор / без зала · минимум инвентар (топка по желание, постелка)",
        f"**Основен акцент:** {main_focus or '—'} · **Вторичен:** {secondary_focus or '—'}",
        "",
        "## Методически насоки (БФВ)",
    ]
    if principles:
        for i, p in enumerate(principles, 1):
            lines.append(f"{i}. {p}")
    else:
        lines.append("1. Качество на движението преди количество.")
        lines.append("2. Меко приземяване; без болка в стави.")
    if cues:
        lines.append("")
        lines.append("**Подсказки:** " + " · ".join(cues))

    lines.extend(
        [
            "",
            f"## 1. Загрявка (~{warm} мин)",
            "- Леко място / маршируване на място 1–2 мин.",
            "- Динамични кръгове: глезени, колене, ханш, рамене — по 8–10 във всяка посока.",
            "- Активация: 8 клякания + 8 напади на крак (бавно).",
            "",
            f"## 2. Координация (~{coord} мин)",
            "- Стълбичка на място (или маркирани линии с тиксо): 2–3 модела × 20–30 сек.",
            "- Ритъм с ръце и крака заедно — 2×30 сек.",
            "- Баланс на един крак — 2×20 сек на страна.",
            "",
            f"## 3. Физически серии (~{phys} мин)",
            "- Клек до удобна дълбочина — 3×8–10 (контрол надолу 2 сек).",
            "- Планк / раменна опора — 3×20–30 сек.",
            "- Глутеус мост — 2×10; задръж 2 сек горе.",
            "- Серия: 10 клякания + 20 сек планк — почивка 40 сек — повтори 2 пъти.",
            "",
            f"## 4. Плиометрия — лека (~{plyo} мин)",
            "- Подскоци на място с меко кацане — 3×6.",
            "- Странични прескачания през линия — 2×8 на страна.",
            "- Drop в клек (от полупръсти) и задръж 1 сек — 2×6.",
            "- *Спри при умора или болка в колене/глезени.*",
            "",
            f"## 5. Фокус по диагнозата (~{focus} мин)",
        ]
    )
    lines.extend(_focus_lines(main_focus, secondary_focus))

    lines.extend(
        [
            "",
            f"## 6. Възстановяване (~{cool} мин)",
            "- Спокоен стречинг: прасци, задно бедро, гърди, рамене — по 20–30 сек.",
            "- 5 дълбоки вдишвания през носа / издишвания през устата.",
            "",
            "## Правила за вкъщи",
            "- По-добре по-малко повторения с чиста техника, отколкото бързане.",
            "- Между сериите: 20–40 сек почивка; пий вода.",
            "- Без максимални скокове и без удари към твърд таван/мебели.",
            "",
            "---",
            "*Текстов план по националната методика БФВ — без упражнения от библиотеката. За индивидуална работа извън залата.*",
        ]
    )
    return "\n".join(lines)
