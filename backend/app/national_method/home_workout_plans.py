def _age_band_for_athlete(birth_year: Optional[int], gender: Optional[str] = None) -> str:
    if not birth_year:
        return "U14"
    from datetime import date

    age = date.today().year - int(birth_year)
    return resolve_age_band({"age": age, "gender": gender})


def _focus_lines(main_focus: str, secondary_focus: Optional[str]) -> list[str]:
    lines: list[str] = []
    for key in (main_focus, secondary_focus):
        if not key:
            continue
        block = _FOCUS_HOME_BLOCKS.get(key)
        if block:
            lines.append(f"**{key}**")
            lines.extend(f"- {x}" for x in block)
    if not lines:
        lines.append("**Общ акцент**")
        lines.extend(f"- {x}" for x in _DEFAULT_FOCUS)
    return lines


def build_home_workout_text(
    *,
    athlete_name: str,
    birth_year: Optional[int] = None,
    gender: Optional[str] = None,
    main_focus: str,
    secondary_focus: Optional[str] = None,
    duration_min: int = 30,
) -> str:
    """Сглобява естествен текстов план за вкъщи (без Drill библиотека)."""
    total = max(20, min(45, int(duration_min)))
    age_band = _age_band_for_athlete(birth_year, gender)
    knowledge = get_age_knowledge(age_band)
    principles = (knowledge.get("principles") or [])[:3]
    cues = (knowledge.get("coach_cues") or [])[:3]

    warm = max(4, total // 7)
    coord = max(5, total // 5)
    phys = max(5, total // 5)
    plyo = max(5, total // 6)
    focus = max(5, total - warm - coord - phys - plyo - 3)
    cool = 3

    lines = [
        f"# Домашна тренировка — {athlete_name}",
        f"**Възрастова група (методика):** {age_band} · **Продължителност:** ~{total} мин",
        f"**Условия:** вкъщи / двор · топка / стена / стол (по желание)",
        f"**Основен акцент:** {main_focus or '—'} · **Вторичен:** {secondary_focus or '—'}",
        "",
        "## Методически насоки",
        "- Плиометриката = експлозивни движения (бързо разтягане → мощно свиване). За млади спортисти: **леки** серии, меко кацане, без максимални скокове всеки ден.",
        "- Между тежки скокове: 10–20 сек почивка; между серии: 30–60 сек. Не тренирай еднакви мускулни групи два дни подред с висока интензивност.",
        "- Приоритет: техника и контрол, не брой повторения „на сила“.",
    ]
    if principles:
        lines.append("")
        lines.append("**От методиката БФВ за възрастта:**")
        for i, p in enumerate(principles, 1):
            lines.append(f"{i}. {p}")
    if cues:
        lines.append("")
        lines.append("**Подсказки:** " + " · ".join(cues))

    lines.extend(
        [
            "",
            f"## 1. Загрявка (~{warm} мин)",
            "- Маршируване / леко място 1–2 мин.",
            "- Подскоци с пляскане над глава (jumping jacks) — 2×20 (леко).",
            "- Динамични кръгове: глезени, колене, ханш, рамене — по 8–10.",
            "- Активация: 8 въздушни клякания + 8 напади на крак (бавно).",
            "",
            f"## 2. Координация и ритъм (~{coord} мин)",
            "- Стълбичка на място / линии с тиксо: 3 модела × 20–30 сек (почивка 20 сек).",
            "- Бягане на място с високо коляно — 2×20 сек (контрол, не спринт до отказ).",
            "- Баланс на един крак — 2×20 сек на страна; при нужда докосни стената.",
            "- Ритъм ръце–крака заедно — 2×30 сек.",
            "",
            f"## 3. Физически серии — сила / стабилност (~{phys} мин)",
            "- Въздушни клякания — 3×8–10 (2 сек надолу).",
            "- Стенна седалка — 2×20–30 сек.",
            "- Лицеви опори (или от колене / към стена) — 2×6–10.",
            "- Планк на предмишници — 3×20–30 сек.",
            "- Напади напред — 2×6 на крак.",
            "- Кофички от стол (ако е стабилен) — 2×6–8 **или** глутеус мост 2×10.",
            "- Почивка между сериите: 40–60 сек.",
            "",
            f"## 4. Плиометрия — лека / скокова (~{plyo} мин)",
            "_Експлозивно, но контролирано. Меко кацане. Спри при болка._",
            "- Клек с отскок (малък отскок) — 3×5; 15 сек между повторенията.",
            "- Жабешки скокове напред (къси) — 2×6.",
            "- Странични прескачания през линия — 2×8 на страна.",
            "- Подскоци на място с високо коляно — 2×8 (леко).",
            "- Планк-джак (крака встрани–заедно в планк) — 2×8 **или** планински катерач 2×20 сек.",
            "- *Не прави максимални „box jumps“ / бърпита всеки ден — 1–2 пъти седмично е достатъчно за тази възраст.*",
            "",
            f"## 5. Фокус по диагнозата (~{focus} мин)",
        ]
    )
    lines.extend(_focus_lines(main_focus, secondary_focus))

    lines.extend(
        [
            "",
            f"## 6. Разпускане / стречинг (~{cool} мин)",
            "- Прасци, задно бедро, квадрицепс, гърди, рамене — по 20–30 сек.",
            "- 5 дълбоки вдишвания през носа / издишвания през устата.",
            "",
            "## Как да ползваш плана",
            "- 1–2 домашни сесии седмично; не натоварвай скокове два дни подред.",
            "- Пий вода; между блоковете си почини според усещането.",
            "- Ако няма топка/стол — пропусни тези варианти и остави имитациите без уреди.",
            "",
            "---",
            "*Текстов домашен план (методика БФВ + базови силови/плиометрични серии). "
            "Не ползва библиотеката с упражнения от залата.*",
        ]
    )
    return "\n".join(lines)
