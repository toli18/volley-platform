def _parse_u14_from_txt(text: str) -> dict[tuple[str, int], dict[str, Any]]:
    """Парсва U14-ПОДГ/СЪСТ-01 от учебника."""
    start = text.find("ВЪЗРАСТОВА ГРУПА: UNDER 13 & UNDER 14")
    end = text.find("ВЪЗРАСТОВА ГРУПА: UNDER 15 & UNDER 16", start + 1)
    if start < 0 or end < 0:
        return {}
    block = text[start:end]
    matches = list(U14_HEADER_RE.finditer(block))
    out: dict[tuple[str, int], dict[str, Any]] = {}
    for i, m in enumerate(matches):
        phase, num_s, title = m.groups()
        num = int(num_s)
        chunk_end = matches[i + 1].start() if i + 1 < len(matches) else len(block)
        body = block[m.end() : chunk_end].strip()
        body = re.split(r"\.\.\.\[Следват", body)[0].strip()
        code = f"U14-{phase.upper()}-{num:02d}"
        out[(phase.upper(), num)] = {
            "code": code,
            "band": "U14",
            "phase": phase.upper(),
            "title_bg": f"{code}: {title.strip()}",
            "body_bg": body,
        }
    return out


def _plan_item(band: str, phase: str, num: int, title: str, body: str) -> dict[str, Any]:
    prefix = "U13" if band == "U13" else "U14"
    code = f"{prefix}-{phase}-{num:02d}"
    return {
        "code": code,
        "band": band,
        "phase": phase,
        "title_bg": f"{code}: {title}",
        "body_bg": body.strip(),
    }


def _lighten_for_u13(body: str) -> str:
    """По-лек вариант за U13."""
    body = re.sub(r"4 серии", "3 серии", body)
    body = re.sub(r"15 повторения", "12 повторения", body)
    body = re.sub(r"до 25", "до 21", body)
    body = re.sub(r"6v6", "6v6 (кратки геймове при нужда)", body)
    return U13_NOTE + body


def all_u14_plans() -> list[dict[str, Any]]:
    txt = TEXTBOOK_TXT.read_text(encoding="utf-8") if TEXTBOOK_TXT.is_file() else ""
    parsed = _parse_u14_from_txt(txt)
    plans: list[dict[str, Any]] = []

    for n in range(1, 11):
        key = ("ПОДГ", n)
        if key in parsed:
            plans.append(parsed[key])
        elif n in U14_PODG_GENERATED:
            title, body = U14_PODG_GENERATED[n]
            plans.append(_plan_item("U14", "ПОДГ", n, title, body))

    for n in range(1, 21):
        key = ("СЪСТ", n)
        if key in parsed:
            plans.append(parsed[key])
        elif n in U14_SAST_GENERATED:
            title, body = U14_SAST_GENERATED[n]
            plans.append(_plan_item("U14", "СЪСТ", n, title, body))

    return plans


def all_u13_plans() -> list[dict[str, Any]]:
    """U13 — същата структура като U14, адаптирана за 12–13 г."""
    out: list[dict[str, Any]] = []
    for p in all_u14_plans():
        code = p["code"].replace("U14-", "U13-", 1)
        title = p["title_bg"].replace("U14-", "U13-", 1)
        out.append(
            {
                "code": code,
                "band": "U13",
                "phase": p["phase"],
                "title_bg": title,
                "body_bg": _lighten_for_u13(p["body_bg"]),
            }
        )
    return out
