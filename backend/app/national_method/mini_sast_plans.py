def _parse_txt_block(text: str) -> dict[int, dict[str, Any]]:
    """Парсва детайлния блок MINI-СЪСТ от bvf_textbook_bg.txt."""
    start_marker = "MINI-СЪСТ-01: Посрещане на долен сервис под напрежение"
    end_marker = "МИНИ ВОЛЕНБОЛ (8–10 ГОДИНИ)"
    start = text.find(start_marker)
    end = text.find(end_marker, start + 1)
    if start < 0 or end < 0:
        return {}
    block = text[start:end]
    matches = list(SESSION_HEADER_RE.finditer(block))
    out: dict[int, dict[str, Any]] = {}
    for i, m in enumerate(matches):
        num = int(m.group(1))
        title = m.group(2).strip()
        chunk_start = m.end()
        chunk_end = matches[i + 1].start() if i + 1 < len(matches) else len(block)
        body = block[chunk_start:chunk_end].strip()
        if num == 12 and "01:00-01:20" not in body:
            body += MINI_SAST_12_TAIL.strip()
        code = f"MINI-СЪСТ-{num:02d}"
        out[num] = {
            "code": code,
            "band": "mini",
            "phase": "СЪСТ",
            "title_bg": f"{code}: {title}",
            "body_bg": body,
        }
    return out


def all_mini_sast_plans() -> list[dict[str, Any]]:
    """Връща 20 пълни MINI-СЪСТ конспекта."""
    txt = TEXTBOOK_TXT.read_text(encoding="utf-8") if TEXTBOOK_TXT.is_file() else ""
    parsed = _parse_txt_block(txt)
    plans: list[dict[str, Any]] = []
    for n in range(1, 21):
        if n in parsed:
            plans.append(parsed[n])
        elif n in MINI_SAST_GENERATED:
            title, body = MINI_SAST_GENERATED[n]
            code = f"MINI-СЪСТ-{n:02d}"
            plans.append(
                {
                    "code": code,
                    "band": "mini",
                    "phase": "СЪСТ",
                    "title_bg": f"{code}: {title}",
                    "body_bg": body.strip(),
                }
            )
    return plans
