def _normalize_city(city: Optional[str]) -> str:
    """Сваля представки (гр./с.), интервали и регистър за стабилно сравнение."""
    if not city:
        return ""
    value = city.strip().lower()
    for prefix in ("гр.", "гр ", "с.", "с ", "град ", "село "):
        if value.startswith(prefix):
            value = value[len(prefix):].strip()
    # Премахва кавички и излишни интервали.
    value = value.replace("„", "").replace("“", "").replace('"', "").strip()
    return " ".join(value.split())


# Изграждаме обратния индекс ГРАД(норм.) → РЕГИОН еднократно при импорт.
CITY_TO_REGION: dict[str, str] = {}
for _region, _cities in _REGION_CITIES.items():
    for _c in _cities:
        CITY_TO_REGION[_normalize_city(_c)] = _region


def region_for_city(city: Optional[str]) -> Optional[str]:
    """Връща региона по град или None, ако градът не е разпознат."""
    return CITY_TO_REGION.get(_normalize_city(city))
